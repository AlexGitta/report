#!/usr/bin/env node
// Builds supabase/seed_contacts_emails.sql from data/council_emails.csv: published council inboxes
// for street/environment reports (authority_contacts.email, priority 200).
//
// CSV columns: authority_gss,authority_name,scope,email,source_url,confidence,notes,checked_date
//   scope = <category slug>            -> one row for that category
//         | group:<category_group>     -> one row per category in the group, except categories that
//                                         have their own CSV row for the same authority
//         | all                        -> one catch-all row (category_id null, category_group null)
//   confidence = page | pdf | snippet
//
// Group scopes are expanded to per-category rows on purpose: pickContact (route-report) prefers any
// category-specific row over a group-level row regardless of priority, so a group-level email row would
// always lose to the per-category GOV.UK Local Links signposts.
//
// Every generated row has notes 'Email: <confidence> · <source_url>'; the SQL first deletes rows with
// notes like 'Email:%', so it is safe to re-run and never touches other contacts. Unknown GSS codes and
// slugs drop out through the joins on authorities and categories.
//
// Usage: node data/build_emails.mjs   (Node 22+, no dependencies)

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const IN = join(here, 'council_emails.csv');
const OUT = join(here, '..', 'supabase', 'seed_contacts_emails.sql');
const PRIORITY = 200;

const COLUMNS = ['authority_gss', 'authority_name', 'scope', 'email', 'source_url', 'confidence', 'notes', 'checked_date'];
const GROUPS = new Set(['roads', 'waste', 'street_scene', 'community_safety']);
const CONFIDENCE = new Set(['page', 'pdf', 'snippet']);
const EMAIL = /^[A-Za-z0-9._%+'&-]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$/;

/** RFC 4180-ish CSV parser: quoted fields, doubled quotes, CRLF or LF. */
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some((f) => f !== '')) rows.push(row);
      row = [];
    } else field += ch;
  }
  row.push(field);
  if (row.some((f) => f !== '')) rows.push(row);
  return rows;
}

const sql = (s) => `'${String(s).replace(/'/g, "''")}'`;

const [header, ...body] = parseCsv((await readFile(IN, 'utf8')).replace(/^﻿/, ''));
if (header.join(',') !== COLUMNS.join(',')) throw new Error(`unexpected CSV header: ${header.join(',')}`);

const errors = [];
const seen = new Set();
const records = [];
body.forEach((cols, i) => {
  const line = i + 2;
  if (cols.length !== COLUMNS.length) return errors.push(`line ${line}: ${cols.length} columns`);
  const r = Object.fromEntries(COLUMNS.map((c, j) => [c, cols[j].trim()]));
  if (!/^E0[6-9]\d{6}$|^E10\d{6}$/.test(r.authority_gss)) errors.push(`line ${line}: bad GSS ${r.authority_gss}`);
  if (!EMAIL.test(r.email)) errors.push(`line ${line}: bad email ${r.email}`);
  if (!CONFIDENCE.has(r.confidence)) errors.push(`line ${line}: bad confidence ${r.confidence}`);
  if (!/^https?:\/\//.test(r.source_url)) errors.push(`line ${line}: bad source_url`);
  let kind, scope;
  if (r.scope === 'all') { kind = 'all'; scope = ''; }
  else if (r.scope.startsWith('group:')) {
    kind = 'group'; scope = r.scope.slice(6);
    if (!GROUPS.has(scope)) errors.push(`line ${line}: unknown group ${scope}`);
  } else if (/^[a-z_]+$/.test(r.scope)) { kind = 'category'; scope = r.scope; }
  else errors.push(`line ${line}: bad scope ${r.scope}`);
  const key = `${r.authority_gss}|${r.scope}|${r.email.toLowerCase()}`;
  if (seen.has(key)) errors.push(`line ${line}: duplicate ${key}`);
  seen.add(key);
  records.push({ ...r, kind, scopeValue: scope, email: r.email.toLowerCase() });
});
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

records.sort((a, b) => a.authority_gss.localeCompare(b.authority_gss) || a.scope.localeCompare(b.scope));
const values = records.map((r) =>
  `  (${sql(r.authority_gss)}, ${sql(r.kind)}, ${sql(r.scopeValue)}, ${sql(r.email)}, ${sql(`Email: ${r.confidence} · ${r.source_url}`)})`);

const authorities = new Set(records.map((r) => r.authority_gss));
const out = `-- Generated by data/build_emails.mjs from data/council_emails.csv. Do not edit by hand.
-- Published council email inboxes for street/environment reports (${records.length} CSV rows, ${authorities.size} authorities).
-- priority ${PRIORITY} beats hand-verified form links (100) and GOV.UK Local Links signposts (0).
-- group:<g> scopes are expanded to one row per category in the group (skipping categories that have
-- their own row for that authority), because pickContact prefers category rows over group rows.
-- 'all' scopes become catch-all rows (category_id and category_group null).

delete from public.authority_contacts where notes like 'Email:%';

with v(authority_gss, kind, scope, email, notes) as (values
${values.join(',\n')}
)
insert into public.authority_contacts (authority_gss, category_id, category_group, email, priority, notes)
select v.authority_gss, c.id, c.category_group, v.email, ${PRIORITY}, v.notes
from v
join public.authorities a on a.gss_code = v.authority_gss
join public.categories c
  on (v.kind = 'category' and c.slug = v.scope)
  or (v.kind = 'group' and c.category_group::text = v.scope
      and not exists (select 1 from v v2
                       where v2.authority_gss = v.authority_gss and v2.kind = 'category' and v2.scope = c.slug))
union all
select v.authority_gss, null, null, v.email, ${PRIORITY}, v.notes
from v
join public.authorities a on a.gss_code = v.authority_gss
where v.kind = 'all';
`;
await writeFile(OUT, out);

const byKind = records.reduce((m, r) => ((m[r.kind] = (m[r.kind] || 0) + 1), m), {});
console.log(`wrote ${OUT}: ${records.length} rows (${JSON.stringify(byKind)}), ${authorities.size} authorities`);
